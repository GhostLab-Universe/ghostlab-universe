"""Regenerate published schemas, core-derived examples and the TS example check.

    python -m ghostlab.contracts.export          # write files
    python -m ghostlab.contracts.export --check  # exit 1 on drift

Pydantic models are the source; schemas/v1 is the published canonical form and
web types are generated from schemas/v1/contracts.bundle.json.
"""

import argparse
import hashlib
import json
import sys
import tempfile
from pathlib import Path

from pydantic.json_schema import models_json_schema

from ..capsule import export_capsule
from ..core import Fixture, Scenario, experiment, run
from .registry import BY_NAME, CONTRACT_SET_VERSION, CONTRACTS

ROOT = Path(__file__).resolve().parents[3]
DRAFT = "https://json-schema.org/draft/2020-12/schema"
GENERATED = "Generated by `python -m ghostlab.contracts.export`. Do not edit."


def _json(value) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def _untitled_properties(schema):
    """Drop per-field titles so generated TS inlines field types; model titles stay."""
    if isinstance(schema, list):
        return [_untitled_properties(item) for item in schema]
    if not isinstance(schema, dict):
        return schema
    result = {key: _untitled_properties(value) for key, value in schema.items()}
    if isinstance(schema.get("properties"), dict):
        result["properties"] = {name: {k: v for k, v in _untitled_properties(prop).items()
                                       if k != "title"}
                                for name, prop in schema["properties"].items()}
    return result


def contract_schemas() -> dict[str, str]:
    files = {}
    for contract in CONTRACTS:
        schema = _untitled_properties(contract.model.model_json_schema(mode="validation"))
        schema = {"$schema": DRAFT, "$id": contract.schema_id, **schema}
        files[f"schemas/v1/{contract.name}.schema.json"] = _json(schema)
    _, defs = models_json_schema([(c.model, "validation") for c in CONTRACTS],
                                 ref_template="#/$defs/{model}")
    bundle = {
        "$schema": DRAFT, "$id": f"urn:ghostlab:{CONTRACT_SET_VERSION}",
        "title": "GhostLabContracts", "description": GENERATED,
        "anyOf": [{"$ref": f"#/$defs/{c.model.__name__}"} for c in CONTRACTS],
        "$defs": _untitled_properties(defs["$defs"]),
    }
    files["schemas/v1/contracts.bundle.json"] = _json(bundle)
    index = {
        "contract_set": CONTRACT_SET_VERSION, "note": GENERATED,
        "contracts": [{
            "name": c.name, "version": c.version, "type": c.model.__name__,
            "schema": f"v1/{c.name}.schema.json", "id": c.schema_id,
            "producer": c.producer, "consumers": list(c.consumers),
            "model_facing": c.model_facing,
            "sha256": hashlib.sha256(files[f"schemas/v1/{c.name}.schema.json"]
                                     .encode()).hexdigest(),
        } for c in CONTRACTS],
    }
    files["schemas/v1/index.json"] = _json(index)
    return files


def core_examples() -> dict[str, str]:
    """Examples produced by executing the synthetic worlds, not hand-written."""
    fixture = Fixture()
    result = experiment(fixture)
    files = {
        "examples/contracts/core/experiment_result.refund_demo.json": _json(result),
        "examples/contracts/core/reality_diff.refund_demo.json": _json(result["diff"]),
        "examples/contracts/core/run_result.faulted_vulnerable.json": _json(result["faulted"]),
        "examples/contracts/core/run_result.budget_exhausted.json":
            _json(run(fixture, Scenario(max_tool_calls=1), "vulnerable")),
    }
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "capsule.json"
        export_capsule(path, fixture, Scenario(timeout_after_commit=True), result["faulted"])
        capsule = json.loads(path.read_text(encoding="utf-8"))
        files["examples/contracts/core/capsule_v1.refund_failure.json"] = _json(capsule)
    # Contract set 1.1: reviewed pack manifests, and refund evidence in the generic form.
    from . import world_refund
    from .world_packs import PACKS
    for version, world in PACKS.items():
        name = version.split("/")[0].replace("-", "_")
        files[f"examples/contracts/core/world_pack.{name}.json"] = _json(
            world.model_dump(mode="json"))
    dump = lambda model: _json(model.model_dump(mode="json"))  # noqa: E731
    files.update({
        "examples/contracts/core/world_run_result.refund_faulted.json":
            dump(world_refund.run_to_world(result["faulted"])),
        "examples/contracts/core/world_reality_diff.refund_demo.json":
            dump(world_refund.diff_to_world(result["diff"])),
        "examples/contracts/core/world_scenario.refund_timeout.json":
            dump(world_refund.scenario_to_world({"timeout_after_commit": True,
                                                 "max_tool_calls": 20})),
        "examples/contracts/core/capsule_v2.refund_failure.json":
            dump(world_refund.capsule_v1_to_v2(capsule)),
    })
    files.update(_capsule_v3_examples(capsule))
    files.update(_journey_examples())
    return files


def _capsule_v3_examples(capsule: dict) -> dict[str, str]:
    """v3 capsules from executed refund evidence: a plain v2 upgrade, a recorded
    capsule with full P1 provenance, and a fresh-adapter retest (a new experiment,
    not a replay claim). Nothing here is hand-written evidence."""
    from ..adapters.refund_env import (ENVIRONMENT_ID, ENVIRONMENT_VERSION, FIXTURE_NAME,
                                       REFUND_INVARIANTS, RefundEnvironment)
    from ..adapters.refund_target import VULNERABLE
    from ..core import ADAPTER_VERSION, Fixture, Scenario, run
    from . import world_refund
    from .capsule_v3 import CapsuleV3, capsule_digest, capsule_v2_to_v3, fixture_digest
    dump = lambda model: _json(model.model_dump(mode="json"))  # noqa: E731
    core = "examples/contracts/core"
    v2 = world_refund.capsule_v1_to_v2(capsule)

    def provenance(payload, replay_kind, retest=None):
        fired = sorted(RefundEnvironment().faults_fired(payload["scenario"],
                                                        payload["run"]["trace"]))
        return {
            "replay_kind": replay_kind, "environment_id": ENVIRONMENT_ID,
            "environment_version": ENVIRONMENT_VERSION, "fixture_name": FIXTURE_NAME,
            "fixture_sha256": fixture_digest(payload["fixture"]),
            # The engine verifier version, pinned by tests/contracts/test_capsule_v3.py
            # (export stays on the light contracts path; it must not import orchestration).
            "rule_versions": {name: "refund-verifier-1" for name in REFUND_INVARIANTS},
            "faults_fired": fired, "config": {}, "external_dependencies": [],
            "truncated": False, "retest_adapter_id": retest[0] if retest else None,
            "retest_adapter_version": retest[1] if retest else None,
        }

    def envelope(payload):
        return {"payload": payload, "sha256": capsule_digest(payload)}

    v2json = v2.payload.model_dump(mode="json")
    files = {f"{core}/capsule_v3.refund_failure.json": dump(capsule_v2_to_v3(v2))}
    recorded = {**v2json, "schema_version": 3, "provenance": provenance(v2json, "recorded")}
    files[f"{core}/capsule_v3.refund_provenance.json"] = dump(
        CapsuleV3.model_validate(envelope(recorded)))
    # Fresh-adapter retest: the vulnerable adapter runs again from the same fixture.
    fixture = Fixture()
    scenario = Scenario(timeout_after_commit=True)
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "capsule.json"
        export_capsule(path, fixture, scenario, run(fixture, scenario, VULNERABLE))
        retest_v1 = json.loads(path.read_text(encoding="utf-8"))
    retest_v2 = world_refund.capsule_v1_to_v2(retest_v1).payload.model_dump(mode="json")
    retest = {**retest_v2, "schema_version": 3,
              "provenance": provenance(retest_v2, "retest", (VULNERABLE, ADAPTER_VERSION))}
    files[f"{core}/capsule_v3.refund_retest.json"] = dump(
        CapsuleV3.model_validate(envelope(retest)))
    return files

def _journey_examples() -> dict[str, str]:
    """``group-journey/1`` evidence from executing M02's engine: the naive adapter
    delivers a message queued before its recipient's sharing was revoked."""
    from ..worlds import journey_capsule
    from .capsule_v3 import capsule_v2_to_v3
    from .world import CapsuleV2
    from ..worlds.journey import JourneyFixture, JourneyScenario, scenario_json
    from ..worlds.journey_run import fault_scenarios, findings, reality_diff, run
    fixture = JourneyFixture()
    data = fault_scenarios(fixture)["sharing_revoked_while_queued"]
    baseline = run(fixture, JourneyScenario.from_json(scenario_json()), "journey-naive")
    faulted = run(fixture, JourneyScenario.from_json(data), "journey-naive")
    [finding] = [f for f in findings(fixture, faulted, "journey-run-1", "2026-10-29T10:00:05Z")
                 if f["invariant"] == "delivered_messages_permitted"]
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "capsule.json"
        journey_capsule.export_capsule(path, fixture, data, faulted)
        capsule = json.loads(path.read_text(encoding="utf-8"))
    core = "examples/contracts/core"
    return {f"{core}/world_run_result.journey_fixture.json": _json(faulted),
            f"{core}/world_reality_diff.journey_fixture.json":
                _json(reality_diff(fixture, baseline, faulted)),
            f"{core}/world_invariant_finding.journey_revoked_delivery.json": _json(finding),
            f"{core}/capsule_v2.journey_fixture.json": _json(capsule),
            f"{core}/capsule_v3.journey_fixture.json": _json(
                capsule_v2_to_v3(CapsuleV2.model_validate(capsule)).model_dump(mode="json"))}


def example_files(root: Path, generated: dict[str, str]) -> dict[str, str]:
    examples = {str(p.relative_to(root).as_posix()): p.read_text(encoding="utf-8")
                for p in sorted((root / "examples/contracts").glob("*.json"))}
    examples.update({k: v for k, v in generated.items() if k.startswith("examples/")})
    return dict(sorted(examples.items()))


def contract_for(example_path: str):
    return BY_NAME[Path(example_path).name.split(".", 1)[0]]


def typescript_check(examples: dict[str, str]) -> str:
    lines = [f"// {GENERATED}",
             "// Each published example must type-check against the generated contracts.",
             'import type * as C from "./contracts";', ""]
    for path, text in examples.items():
        contract = contract_for(path)
        const = Path(path).name.removesuffix(".json").replace(".", "__")
        literal = json.dumps(json.loads(text), indent=2, sort_keys=True)
        lines.append(f"export const {const}: C.{contract.model.__name__} = {literal};\n")
    return "\n".join(lines)


def render_all(root: Path = ROOT) -> dict[str, str]:
    files = {**contract_schemas(), **core_examples()}
    files["schemas/typescript/examples.check.ts"] = typescript_check(example_files(root, files))
    return files


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    drift = []
    for relative, text in render_all(args.root).items():
        path = args.root / relative
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        drift.append(relative)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    for relative in drift:
        print(("drift: " if args.check else "wrote: ") + relative)
    return 1 if args.check and drift else 0


if __name__ == "__main__":
    sys.exit(main())
