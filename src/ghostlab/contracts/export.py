"""Regenerate published schemas, core-derived examples and the TS example check.

    python -m ghostlab.contracts.export          # write files
    python -m ghostlab.contracts.export --check  # exit 1 on drift

Pydantic models are the source; schemas/v1 is the published canonical form and
web types are generated from schemas/v1/contracts.bundle.json.
"""

import argparse
import hashlib
import json
import sys
import tempfile
from pathlib import Path

from pydantic.json_schema import models_json_schema

from ..capsule import export_capsule
from ..core import Fixture, Scenario, experiment, run
from .registry import BY_NAME, CONTRACT_SET_VERSION, CONTRACTS

ROOT = Path(__file__).resolve().parents[3]
DRAFT = "https://json-schema.org/draft/2020-12/schema"
GENERATED = "Generated by `python -m ghostlab.contracts.export`. Do not edit."


def _json(value) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def _untitled_properties(schema):
    """Drop per-field titles so generated TS inlines field types; model titles stay."""
    if isinstance(schema, list):
        return [_untitled_properties(item) for item in schema]
    if not isinstance(schema, dict):
        return schema
    result = {key: _untitled_properties(value) for key, value in schema.items()}
    if isinstance(schema.get("properties"), dict):
        result["properties"] = {name: {k: v for k, v in _untitled_properties(prop).items()
                                       if k != "title"}
                                for name, prop in schema["properties"].items()}
    return result


def contract_schemas() -> dict[str, str]:
    files = {}
    for contract in CONTRACTS:
        schema = _untitled_properties(contract.model.model_json_schema(mode="validation"))
        schema = {"$schema": DRAFT, "$id": contract.schema_id, **schema}
        files[f"schemas/v1/{contract.name}.schema.json"] = _json(schema)
    _, defs = models_json_schema([(c.model, "validation") for c in CONTRACTS],
                                 ref_template="#/$defs/{model}")
    bundle = {
        "$schema": DRAFT, "$id": f"urn:ghostlab:{CONTRACT_SET_VERSION}",
        "title": "GhostLabContracts", "description": GENERATED,
        "anyOf": [{"$ref": f"#/$defs/{c.model.__name__}"} for c in CONTRACTS],
        "$defs": _untitled_properties(defs["$defs"]),
    }
    files["schemas/v1/contracts.bundle.json"] = _json(bundle)
    index = {
        "contract_set": CONTRACT_SET_VERSION, "note": GENERATED,
        "contracts": [{
            "name": c.name, "version": c.version, "type": c.model.__name__,
            "schema": f"v1/{c.name}.schema.json", "id": c.schema_id,
            "producer": c.producer, "consumers": list(c.consumers),
            "model_facing": c.model_facing,
            "sha256": hashlib.sha256(files[f"schemas/v1/{c.name}.schema.json"]
                                     .encode()).hexdigest(),
        } for c in CONTRACTS],
    }
    files["schemas/v1/index.json"] = _json(index)
    return files


def core_examples() -> dict[str, str]:
    """Examples produced by executing the synthetic refund core, not hand-written."""
    fixture = Fixture()
    result = experiment(fixture)
    files = {
        "examples/contracts/core/experiment_result.refund_demo.json": _json(result),
        "examples/contracts/core/reality_diff.refund_demo.json": _json(result["diff"]),
        "examples/contracts/core/run_result.faulted_vulnerable.json": _json(result["faulted"]),
        "examples/contracts/core/run_result.budget_exhausted.json":
            _json(run(fixture, Scenario(max_tool_calls=1), "vulnerable")),
    }
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "capsule.json"
        export_capsule(path, fixture, Scenario(timeout_after_commit=True), result["faulted"])
        files["examples/contracts/core/capsule_v1.refund_failure.json"] = _json(
            json.loads(path.read_text(encoding="utf-8")))
    return files


def example_files(root: Path, generated: dict[str, str]) -> dict[str, str]:
    examples = {str(p.relative_to(root).as_posix()): p.read_text(encoding="utf-8")
                for p in sorted((root / "examples/contracts").glob("*.json"))}
    examples.update({k: v for k, v in generated.items() if k.startswith("examples/")})
    return dict(sorted(examples.items()))


def contract_for(example_path: str):
    return BY_NAME[Path(example_path).name.split(".", 1)[0]]


def typescript_check(examples: dict[str, str]) -> str:
    lines = [f"// {GENERATED}",
             "// Each published example must type-check against the generated contracts.",
             'import type * as C from "./contracts";', ""]
    for path, text in examples.items():
        contract = contract_for(path)
        const = Path(path).name.removesuffix(".json").replace(".", "__")
        literal = json.dumps(json.loads(text), indent=2, sort_keys=True)
        lines.append(f"export const {const}: C.{contract.model.__name__} = {literal};\n")
    return "\n".join(lines)


def render_all(root: Path = ROOT) -> dict[str, str]:
    files = {**contract_schemas(), **core_examples()}
    files["schemas/typescript/examples.check.ts"] = typescript_check(example_files(root, files))
    return files


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    drift = []
    for relative, text in render_all(args.root).items():
        path = args.root / relative
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        drift.append(relative)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    for relative in drift:
        print(("drift: " if args.check else "wrote: ") + relative)
    return 1 if args.check and drift else 0


if __name__ == "__main__":
    sys.exit(main())
