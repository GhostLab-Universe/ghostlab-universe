// Generates the typed API surface from the copied M07 OpenAPI document.
// Run from web/: `node src/api/generate.mjs` (or `--check` to detect drift).
// openapi.v1.json is a verbatim copy; refresh it and openapi.source.json together.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const web = createRequire(join(process.cwd(), "package.json"));
const { compile } = await import(pathToFileURL(web.resolve("json-schema-to-typescript")).href);

const here = new URL(".", import.meta.url);
const raw = await readFile(new URL("openapi.v1.json", here), "utf8");
const source = JSON.parse(await readFile(new URL("openapi.source.json", here), "utf8"));
const digest = createHash("sha256").update(raw.replace(/\r\n/g, "\n")).digest("hex");
if (digest !== source.sha256) {
  console.error(`openapi.v1.json is ${digest}, but openapi.source.json records ${source.sha256}`);
  process.exit(1);
}
const doc = JSON.parse(raw);

// Parameter and property titles would each become a pointless named alias.
function withoutTitles(value, keepTitle) {
  if (Array.isArray(value)) return value.map((item) => withoutTitles(item, false));
  if (value === null || typeof value !== "object") return value;
  const copy = {};
  for (const [key, item] of Object.entries(value)) {
    if (key === "title" && !keepTitle && typeof item === "string") continue;
    copy[key] = key === "properties" ? mapValues(item) : withoutTitles(item, false);
  }
  return copy;
}
const mapValues = (object) =>
  Object.fromEntries(Object.entries(object).map(([k, v]) => [k, withoutTitles(v, false)]));

const defs = {};
for (const [name, schema] of Object.entries(doc.components.schemas)) {
  defs[name] = { ...withoutTitles(schema, false), title: name };
}
// An unconstrained schema: M00 generates this one as `unknown` too.
if (Object.keys(defs.JsonValue).length === 1) defs.JsonValue.tsType = "unknown";
const bundle = JSON.parse(JSON.stringify({
  title: "GhostLabApiSchema",
  oneOf: Object.keys(defs).map((name) => ({ $ref: `#/components/schemas/${name}` })),
  $defs: defs,
}).replaceAll("#/components/schemas/", "#/$defs/"));

const banner = [
  `/* Generated by web/src/api/generate.mjs from web/src/api/openapi.v1.json. Do not edit.`,
  `   Source: ${source.source_path} at ${source.source_commit} (${source.source_branch}). */`,
].join("\n");
const types = await compile(bundle, "GhostLabApiSchema", {
  bannerComment: banner,
  additionalProperties: false,
  strictIndexSignatures: true,
  unreachableDefinitions: true,
  format: true,
});

const operations = {};
for (const [path, methods] of Object.entries(doc.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    const success = Object.keys(operation.responses).find((code) => code.startsWith("2"));
    const body = operation.responses[success]?.content?.["application/json"]?.schema;
    const name = body?.$ref?.split("/").pop();
    operations[operation.operationId] = {
      method: method.toUpperCase(),
      path,
      success: Number(success),
      query: (operation.parameters ?? []).filter((p) => p.in === "query").map((p) => p.name),
      queryValues: Object.fromEntries(
        (operation.parameters ?? [])
          .filter((p) => p.in === "query" && p.schema?.enum)
          .map((p) => [p.name, p.schema.enum]),
      ),
      idempotencyKey: (operation.parameters ?? []).some((p) => p.name === "Idempotency-Key"),
      required: name ? doc.components.schemas[name].required ?? [] : [],
    };
  }
}
const operationsFile = [
  banner,
  "",
  `export const OPERATIONS = ${JSON.stringify(operations, null, 2)} as const;`,
  "",
  "export type OperationId = keyof typeof OPERATIONS;",
  "",
].join("\n");

const outputs = { "api.generated.ts": types, "operations.generated.ts": operationsFile };
for (const [name, text] of Object.entries(outputs)) {
  const target = new URL(name, here);
  if (process.argv.includes("--check")) {
    const current = (await readFile(target, "utf8").catch(() => "")).replace(/\r\n/g, "\n");
    if (current !== text) {
      console.error(`drift: web/src/api/${name}`);
      process.exit(1);
    }
    console.log(`${name} matches openapi.v1.json`);
  } else {
    await writeFile(target, text);
    console.log(`wrote web/src/api/${name}`);
  }
}
